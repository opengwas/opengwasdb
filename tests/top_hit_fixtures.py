"""Three small Stores (Dense, Ragged, Hybrid) and the `top_hits()` query matrix.

`QUERY_MATRIX` is what `tests/golden/top_hit_queries.json` pins. The golden file
was generated by running this module against the code at `eb5845b` -- before the
Top-Hit Index module existed -- so a test comparing against it checks the new
reads against the old ones, never the new code against itself.
"""

