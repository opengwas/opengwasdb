from opengwasdb.layouts.hybrid.build import build_hybrid_from_vcf_manifest
from opengwasdb.model.manifest import StoreManifest
from opengwasdb.query import query_store

#: 5e-8 / 5e-6 / 5e-4 are the indexed tiers; 1e-9 and 1e-3 have no tier, so a
#: Ragged Store answers them by scanning its CSR.
THRESHOLDS = (1e-9, 5e-8, 5e-6, 5e-4, 1e-3)

#: conftest's fixture rows (|z| 20, 30, 15, 12) plus two weaker cells, so a tier
#: boundary separates cells: |z| 4.5 and 3.5 clear 5e-4 (z >= 3.48) but not 5e-6
#: (z >= 4.56).
DENSE_EXTRA_ROWS = [
    "a1\tp1\tHeight\tHeight primary\t1\t300\tG\tA\t0.9\t0.2\trs3\tsd",
    "a2\tp2\tDisease\tDisease primary\t1\t200\tT\tC\t0.7\t0.2\trs2\tlog_or",
]


def build_dense(tmp_path: Path) -> Path:
    source = tmp_path / "associations.tsv"
    source.write_text(
        SOURCE_HEADER + "\n" + "\n".join([*SOURCE_ROWS, *DENSE_EXTRA_ROWS]) + "\n",
        encoding="utf-8",
    )
    out = tmp_path / "dense.opengwasdb"
    build_dense_fixture(
        [source], out, store_id="fixture-store", release_id="observed-v1",
        reference_assembly="GRCh37",
    )
    return out


def build_ragged(tmp_path: Path) -> Path:
    """The BESD fixture of test_ragged_build_besd: |z| 5.0, 6.7 / 10.0 / 7.5, 6.0,
    of which 1e-9 (z >= 6.11) keeps three of the five."""
    return _build_ragged_store(tmp_path, name="ragged.opengwasdb")


def build_completed_dense(tmp_path: Path) -> Path:
    """The residual Reference-Completed Dense Store with one imputed cell
    made a decisive top hit (z = 8) and the index rebuilt from the store's own plane.

    Its imputed cells are otherwise all low-|z|, so a top-hit query would have no
    imputed row for `observed_only` to filter (`test_the_completed_fixture_has_an_
    imputed_top_hit` holds the fixture to it).
    """
    out, _, _ = residual_stores.dense_completed(tmp_path)
    encoding = StoreManifest.load(out).encoding
    root = zarr.open_group(str(out / "data.zarr"), mode="r+", zarr_format=3)
    rows, cols = np.where(np.asarray(root["imputed"][:], dtype=bool))
    plane_edits.patch(
        root, encoding, DenseZPlane, rows[:1], cols[:1], np.array([8.0], dtype=np.float32)
    )
    build_top_hit_indexes(out)
    return out


def build_hybrid(tmp_path: Path) -> Path:
    vcf1 = hb._make_vcf(tmp_path, "trait_a", [
        f"1\t{hb.HG19_POS_1}\t.\tA\tG\t.\tPASS\t.\tES:SE:AF\t2.0:0.5:0.2\n",
        f"1\t{hb.HG19_POS_2}\t.\tC\tT\t.\tPASS\t.\tES:SE:AF\t1.5:0.3:0.3\n",
        f"1\t{hb.HG19_POS_3}\t.\tG\tA\t.\tPASS\t.\tES:SE:AF\t0.6:0.2:0.4\n",
    ])
    vcf2 = hb._make_vcf(tmp_path, "trait_b", [
        f"1\t{hb.HG19_POS_1}\t.\tA\tG\t.\tPASS\t.\tES:SE:AF\t6.0:0.5:0.25\n",
        f"1\t{hb.HG19_POS_3}\t.\tG\tA\t.\tPASS\t.\tES:SE:AF\t1.2:0.3:0.45\n",
    ])
    manifest = hb._make_manifest(
        tmp_path, [("trait_a", vcf1, "Trait A"), ("trait_b", vcf2, "Trait B")]
    )
    out = tmp_path / "hybrid.opengwasdb"
    build_hybrid_from_vcf_manifest(
        manifest, out, reference_panel=hb._panel(tmp_path), store_id="hybrid-test",
        release_id="v1", n_workers=1,
    )
    return out


def _plain_value(v: Any) -> Any:
    """A JSON-comparable scalar; NaN is spelled "nan" because NaN != NaN."""
    v = v.item() if hasattr(v, "item") else v
    return "nan" if isinstance(v, float) and v != v else v


def _plain(result: dict[str, np.ndarray]) -> dict[str, list[Any]]:
    return {name: [_plain_value(v) for v in values] for name, values in sorted(result.items())}


def query_matrix(store_path: Path, analysis_ids: list[str]) -> dict[str, dict[str, list[Any]]]:
    """Every `top_hits()` answer the pins cover, keyed by its arguments."""
    query = query_store(store_path)
    out: dict[str, dict[str, list[Any]]] = {}
    for threshold in THRESHOLDS:
        for analysis_id in [None, *analysis_ids, "no-such-analysis"]:
            for limit in (None, 1):
                for observed_only in (False, True):
                    key = f"{threshold:g}|{analysis_id}|{limit}|{observed_only}"
                    out[key] = _plain(query.top_hits(
                        analysis_id=analysis_id, threshold=threshold,
                        limit=limit, observed_only=observed_only,
                    ))
    return out


