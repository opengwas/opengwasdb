#!/usr/bin/env python3
"""Turn `run_spike.py`'s JSON into the markdown tables and every number the ADR quotes.

    pixi run -e dev python benchmarks/rust_spike/summarise_spike.py \\
        docs/benchmark-output/rust_spike_ogs00009.json > docs/benchmark-output/rust_spike_ogs00009_tables.md

Nothing is typed in by hand: ratios are computed per round (the reference's warm median over the
candidate's, from the same interleaved round) and reported as a range across rounds and as the median
of the per-round ratios.  A ratio above 1 means the candidate is faster.
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path
from typing import Any


def _warm(round_record: dict[str, Any]) -> float:
    return statistics.median(round_record["warm_ms"])


def _range(values: list[float]) -> str:
    return f"{min(values):.1f}-{max(values):.1f}"


def _ratio(ref: dict[str, Any], col: dict[str, Any], field: str) -> list[float]:
    out = []
    for r_ref, r_col in zip(ref["rounds"], col["rounds"], strict=True):
        a = r_ref["cold_ms"] if field == "cold" else _warm(r_ref)
        b = r_col["cold_ms"] if field == "cold" else _warm(r_col)
        out.append(a / b)
    return out


def _ratio_text(ratios: list[float]) -> str:
    return f"{statistics.median(ratios):.2f}x ({min(ratios):.2f}-{max(ratios):.2f})"


def main(path: Path) -> None:
    data = json.loads(path.read_text())
    cols = data["columns"]
    reference = data["reference_run"]
    by_key = {(c["shape"], c["stage"], c["run"]): c for c in cols}
    shapes = list(dict.fromkeys(c["shape"] for c in cols))
    lookup_shapes = [s for s in shapes if s.startswith("random_lookup")]
    extra_shapes = [s for s in shapes if not s.startswith("random_lookup")]
    runs = list(dict.fromkeys(c["run"] for c in cols if c["shape"] in lookup_shapes))

    out: list[str] = []
    w = out.append
    w(f"Generated by `summarise_spike.py` from `{path.name}` (commit `{data['commit'][:8]}`, "
      f"{data['measured_at']}). Reference run: `{reference}`.")
    w("")
    w(f"{data['rounds']} interleaved rounds per column; each round is one fresh process per candidate "
      f"(1 cold call, then {data['warm_per_process']} warm calls). Cold = {data['cold_definition']}. "
      f"`--max-start-load` {data['max_start_load']}. zarrs crate {data['zarrs_crate']}.")
    loads = [r["load_1m_at_start"] for c in cols for r in c["rounds"]]
    w(f"1-minute load at the start of a measurement: {min(loads):.1f}-{max(loads):.1f} "
      f"(median {statistics.median(loads):.1f}).")
    w("")

    for stage in ("end_to_end", "decode", "axis_resolution"):
        w(f"## {stage}")
        w("")
        w("Warm: median of the per-round warm medians, then min-max over every warm call. "
          "Ratio = reference / candidate within the same round: median (min-max over rounds).")
        w("")
        w("| shape | run | cold ms (median, min-max) | warm ms (median, min-max) | warm ratio | cold ratio |")
        w("|---|---|---|---|---|---|")
        for shape in lookup_shapes:
            ref = by_key[(shape, stage, reference)]
            for run in runs:
                col = by_key.get((shape, stage, run))
                if col is None:
                    continue
                cold = [r["cold_ms"] for r in col["rounds"]]
                warm_all = [x for r in col["rounds"] for x in r["warm_ms"]]
                warm_med = statistics.median(_warm(r) for r in col["rounds"])
                ratio = "1" if run == reference else _ratio_text(_ratio(ref, col, "warm"))
                cratio = "1" if run == reference else _ratio_text(_ratio(ref, col, "cold"))
                w(f"| {shape.replace('random_lookup_', '')} | {run} | {statistics.median(cold):.1f} "
                  f"({_range(cold)}) | {warm_med:.1f} ({_range(warm_all)}) | {ratio} | {cratio} |")
        w("")

    w("## Attribution (reference run, end to end)")
    w("")
    w("| shape | axis_resolution warm ms | decode warm ms | end_to_end warm ms | decode / end_to_end |")
    w("|---|---|---|---|---|")
    for shape in lookup_shapes:
        a = statistics.median(_warm(r) for r in by_key[(shape, "axis_resolution", reference)]["rounds"])
        d = statistics.median(_warm(r) for r in by_key[(shape, "decode", reference)]["rounds"])
        e = statistics.median(_warm(r) for r in by_key[(shape, "end_to_end", reference)]["rounds"])
        w(f"| {shape.replace('random_lookup_', '')} | {a:.2f} | {d:.1f} | {e:.1f} | {100 * d / e:.1f} % |")
    w("")

    w("## Effective configuration (read back in each child)")
    w("")
    w("| run | codec pipeline class | zarr max_workers | Blosc threads | other |")
    w("|---|---|---|---|---|")
    seen: set[str] = set()
    for c in cols:
        if c["run"] in seen:
            continue
        seen.add(c["run"])
        cfg = c["rounds"][0]["effective_config"]
        if "array_pipeline_class" in cfg:
            other = f"threadpool={c['rounds'][0]['versions']['threadpool']}, zarrs-python={c['rounds'][0]['versions']['zarrs_python']}"
            w(f"| {c['run']} | {cfg['array_pipeline_class']} | {cfg['config_max_workers']} | "
              f"{cfg['blosc_use_threads']} | {other} |")
        else:
            w(f"| {c['run']} | zarrs crate {data['zarrs_crate']} | n/a | n/a | threads={cfg['threads']}, "
              f"codec_concurrent_target={cfg['zarrs_codec_concurrent_target']}, "
              f"RAYON_NUM_THREADS={cfg['rayon_num_threads_env']}, wide ALIDs via caller={cfg['wide_alid_fallback']} |")
    w("")

    w("## Store sizes (apparent bytes of the arrays the lookup reads)")
    w("")
    stores = list(data["store_sizes"])
    if len(stores) == 2:
        base, small = stores
        w(f"`{base}` -> `{small}`")
        w("")
        w("| array | original MiB | re-chunked MiB | change |")
        w("|---|---|---|---|")
        sb, ss = data["store_sizes"][base]["apparent_bytes"], data["store_sizes"][small]["apparent_bytes"]
        tb = ts = 0
        for name in ("z", "se", "eaf", "imputed", "eaf_baseline", "eaf_reference"):
            tb += sb[name]
            ts += ss[name]
            w(f"| {name} | {sb[name] / 2**20:,.0f} | {ss[name] / 2**20:,.0f} | {100 * (ss[name] / sb[name] - 1):+.1f} % |")
        w(f"| total of those six | {tb / 2**20:,.0f} | {ts / 2**20:,.0f} | {100 * (ts / tb - 1):+.1f} % |")
        w("")

    if extra_shapes:
        w("## The harness's other shapes, Python reader on both chunkings (end to end)")
        w("")
        w("Ratio = original chunking / smaller chunk within the same round (above 1: the smaller chunk is faster).")
        w("")
        w("| shape | run | warm ms (median, min-max) | cold ms (median, min-max) | ratio original/smaller |")
        w("|---|---|---|---|---|")
        py_runs = [r for r in runs if r.startswith(reference.rsplit("-", 1)[0])]
        for shape in extra_shapes:
            ref = by_key[(shape, "end_to_end", reference)]
            for run in py_runs:
                col = by_key.get((shape, "end_to_end", run))
                if col is None:
                    continue
                warm_all = [x for r in col["rounds"] for x in r["warm_ms"]]
                cold = [r["cold_ms"] for r in col["rounds"]]
                ratio = "" if run == reference else _ratio_text(_ratio(ref, col, "warm"))
                w(f"| {shape} | {run} | {statistics.median(_warm(r) for r in col['rounds']):.1f} "
                  f"({_range(warm_all)}) | {statistics.median(cold):.1f} ({_range(cold)}) | {ratio} |")
        w("")

    w("## Agreement")
    w("")
    n = sum(1 for c in cols for r in c["rounds"] if r.get("digests_equal_reference"))
    total = sum(len(c["rounds"]) for c in cols if c["stage"] != "axis_resolution")
    w(f"{n} of {total} digested measurements equal the reference's first-call digests "
      f"(Python: first and last call; Rust: cold and warm process). {data.get('agreement', '')}")
    print("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
